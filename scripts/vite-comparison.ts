#!/usr/bin/env bun
/**
 * Bun.build() vs Vite on the same variants x apps: generates the tables in VITE.md from
 * dist/<variant>/<app>/report.json (build.ts) and dist-vite/<variant>/<app>/report.json
 * (build-vite.ts). Hand-written text above the generated marker is preserved (on the first run,
 * the whole existing file is kept as the hand-written part); builds that are
 * missing on either side show as "–".
 *
 *   bun scripts/vite-comparison.ts
 *   --bun=<dir> --vite=<dir>   read reports from there instead of dist/ and dist-vite/
 *   --out=<file>               write there instead of VITE.md
 *
 * The generated section starts with the Svelte source and bundler of each side, and warns if
 * the two sides were built from different Svelte sources.
 */
import { existsSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { ROOT } from './link-svelte.ts';
import { provenanceText, type Report } from '../measure.ts';
import { STACK_ORDER } from '../variants.ts';

const flag = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const SIDES = { Bun: resolve(flag('bun') ?? join(ROOT, 'dist')), Vite: resolve(flag('vite') ?? join(ROOT, 'dist-vite')) };
type Side = keyof typeof SIDES;

// every app in apps/, the two headline apps first
const rank = (app: string) => ((i) => (i < 0 ? 2 : i))(['hello', 'reactive'].indexOf(app));
const APPS = readdirSync(join(ROOT, 'apps'))
	.filter((a) => existsSync(join(ROOT, 'apps', a, 'client.js')))
	.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
	// ...that have been built on both sides
	.filter((app) => Object.values(SIDES).every((dir) => existsSync(join(dir, 'baseline', app, 'report.json'))));
const VARIANTS = ['baseline', 'optimized', 'minimal'];
const n = (x: number) => x.toLocaleString('en-US');
const signed = (x: number) => (x === 0 ? '0' : `${x > 0 ? '+' : '−'}${n(Math.abs(x))}`);
const pct = (x: number, base: number) => `${x - base >= 0 ? '+' : '−'}${Math.abs((100 * (x - base)) / base).toFixed(1)}%`;

const reports = new Map<string, Report | null>();
async function report(side: Side, variant: string, app: string) {
	const key = `${side}:${variant}/${app}`;
	if (!reports.has(key)) {
		const file = join(SIDES[side], variant, app, 'report.json');
		reports.set(key, existsSync(file) ? await Bun.file(file).json() : null);
	}
	return reports.get(key)!;
}
const size = async (side: Side, variant: string, app: string) => (await report(side, variant, app))?.sizes['main.min.js'];

const md: string[] = ['<!-- generated by scripts/vite-comparison.ts; do not edit below this line by hand -->', ''];

// 1. app x variant, side by side
md.push('## Sizes: Bun vs Vite (`main.min.js`)', '');
md.push('Δ is Vite minus Bun: negative means Vite\'s bundle is smaller.', '');
md.push(
	'| app | variant | Bun raw | Vite raw | Δ raw | Bun gzip | Vite gzip | Δ gzip | Bun brotli | Vite brotli | Δ brotli |',
	'| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
);
for (const app of APPS) {
	for (const v of VARIANTS) {
		const bun = await size('Bun', v, app);
		const vite = await size('Vite', v, app);
		const cells = (['raw', 'gzip', 'brotli'] as const).flatMap((k) => [
			bun ? n(bun[k]) : '–',
			vite ? n(vite[k]) : '–',
			bun && vite ? `${signed(vite[k] - bun[k])} (${pct(vite[k], bun[k])})` : '–'
		]);
		md.push(`| ${app} | ${v === 'minimal' ? '**minimal**' : v} | ${cells.join(' | ')} |`);
	}
}
md.push('');

// 2. Bun's best lossless build (baseline-bun) against Vite's plain baseline
md.push('## Bun\'s closest lossless build: `baseline-bun` vs Vite\'s `baseline`', '');
md.push(
	'Every build in this table keeps all of Svelte\'s features. `baseline-bun` is `optimized` plus the post-pass\'s minify steps (postpass-minify.ts). Δ is `baseline-bun` minus Vite\'s `baseline`.',
	''
);
md.push(
	'| app | Vite baseline raw / gzip | Bun baseline | Bun optimized | Bun baseline-bun | Δ raw | Δ gzip | Δ brotli |',
	'| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
);
for (const app of APPS) {
	const vite = await size('Vite', 'baseline', app);
	const cell = async (v: string) => {
		const s = await size('Bun', v, app);
		return s ? `${n(s.raw)} / ${n(s.gzip)}` : '–';
	};
	const best = await size('Bun', 'baseline-bun', app);
	const d = (k: 'raw' | 'gzip' | 'brotli') => (best && vite ? `${signed(best[k] - vite[k])} (${pct(best[k], vite[k])})` : '–');
	md.push(`| ${app} | ${vite ? `${n(vite.raw)} / ${n(vite.gzip)}` : '–'} | ${await cell('baseline')} | ${await cell('optimized')} | **${await cell('baseline-bun')}** | ${d('raw')} | ${d('gzip')} | ${d('brotli')} |`);
}
md.push('');

// 3. the stacking steps under each bundler
md.push('## Stacking under each bundler (gzip)', '');
md.push('The variants of COMPARISON.md\'s stacking table, built by each bundler. Δ is the saving of that step over the row above, for that bundler.', '');
md.push(
	'| variant | hello Bun | Δ | hello Vite | Δ | reactive Bun | Δ | reactive Vite | Δ |',
	'| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
);
const prev: Record<string, number | undefined> = {};
for (const v of STACK_ORDER) {
	const cells: string[] = [];
	for (const app of ['hello', 'reactive']) {
		for (const side of ['Bun', 'Vite'] as const) {
			const gz = (await size(side, v, app))?.gzip;
			const p = prev[`${side}:${app}`];
			cells.push(gz === undefined ? '–' : n(gz), gz !== undefined && p !== undefined ? signed(gz - p) : '');
			if (gz !== undefined) prev[`${side}:${app}`] = gz;
		}
	}
	if (cells.some((c) => c && c !== '–')) md.push(`| \`${v}\` | ${cells.join(' | ')} |`);
}
md.push('');

// 4. where the two bundles differ, module by module
md.push('## Where the bytes differ: per module (`min` bytes)', '');
md.push(
	'Bytes of `main.min.js` attributed to each source module (measure.ts, from the top-level statements of the aligned readable/minified builds), largest difference first. Modules within 50 B of each other are summed into the last row.',
	''
);
for (const app of ['hello', 'reactive']) {
	for (const v of ['baseline', 'minimal']) {
		const [bun, vite] = [await report('Bun', v, app), await report('Vite', v, app)];
		if (!bun?.declarations || !vite?.declarations) continue;
		const bytes = (r: Report) => new Map(r.modules.filter((m) => m.min > 0).map((m) => [m.module, m.min]));
		const [b, w] = [bytes(bun), bytes(vite)];
		const rows = [...new Set([...b.keys(), ...w.keys()])]
			.map((module) => ({ module, bun: b.get(module) ?? 0, vite: w.get(module) ?? 0 }))
			.sort((x, y) => Math.abs(y.vite - y.bun) - Math.abs(x.vite - x.bun));
		const shown = rows.filter((r) => Math.abs(r.vite - r.bun) > 50);
		const rest = rows.filter((r) => Math.abs(r.vite - r.bun) <= 50);
		const [bunTotal, viteTotal] = [bun.sizes['main.min.js'].raw, vite.sizes['main.min.js'].raw];
		md.push(`### ${app} / ${v}: Bun ${n(bunTotal)} B, Vite ${n(viteTotal)} B (${signed(viteTotal - bunTotal)})`, '');
		md.push('| module | Bun | Vite | Δ |', '| --- | ---: | ---: | ---: |');
		for (const r of shown) md.push(`| \`${r.module.replace(/^svelte\/src\//, '')}\` | ${n(r.bun)} | ${n(r.vite)} | ${signed(r.vite - r.bun)} |`);
		const sum = (k: 'bun' | 'vite') => rest.reduce((a, r) => a + r[k], 0);
		if (rest.length) md.push(`| ${rest.length} other modules | ${n(sum('bun'))} | ${n(sum('vite'))} | ${signed(sum('vite') - sum('bun'))} |`);
		md.push('');
	}
}

// provenance, right below the marker: which Svelte and which bundler each side was built with
const stamp: string[] = [];
const sources = new Set<string>();
for (const side of ['Bun', 'Vite'] as const) {
	const found = [...reports].filter(([k, r]) => k.startsWith(`${side}:`) && r).map(([, r]) => r!);
	if (!found.length) {
		stamp.push(`- **${side}:** no reports in \`${SIDES[side]}\``);
		continue;
	}
	const svelte = [...new Set(found.map((r) => `Svelte ${r.svelteVersion} (${r.svelte ? provenanceText(r.svelte) : 'source not recorded'})`))];
	const bundlers = [...new Set(found.map((r) => r.bundler ?? `Bun ${r.bunVersion}`))];
	svelte.forEach((s) => sources.add(s));
	stamp.push(`- **${side}:** ${bundlers.join(', ')}; ${svelte.join('; ')}`);
}
if (sources.size > 1) stamp.push('', '**Warning: the reports were built from different Svelte sources, so the sides are not directly comparable.**');
md.splice(2, 0, ...stamp, '');

const out = resolve(flag('out') ?? join(ROOT, 'VITE.md'));
const existing = existsSync(out) ? await Bun.file(out).text() : '';
const marker = md[0];
// everything above the marker is hand-written; a file without a marker yet is all hand-written
const head = existing.includes(marker) ? existing.slice(0, existing.indexOf(marker)) : existing ? `${existing.trimEnd()}\n\n` : '# VITE: Bun.build() vs Vite\n\n';
await Bun.write(out, head + md.join('\n') + '\n');
console.log(`wrote ${out}`);
