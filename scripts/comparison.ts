#!/usr/bin/env bun
/**
 * Generates the tables in COMPARISON.md from dist/<variant>/<app>/report.json and
 * coverage.json (run `bun run build.ts --all` first). Hand-written text above the
 * generated marker is preserved.
 *
 *   bun scripts/comparison.ts
 *   --out=<file>    write there instead of COMPARISON.md (reports are read from dist/, or from
 *                   SVELTE_LITE_DIST=<dir> for builds made with build.ts --out=<dir>)
 *
 * The generated section starts with the exact Svelte source (ref/tag/sha) recorded in the
 * report.json files it summarises, and warns if they were built from different sources.
 */
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { ROOT } from './link-svelte.ts';
import { loadReport, provenanceText, type Report } from '../measure.ts';
import { STACK_ORDER } from '../variants.ts';

const MAIN_APPS = ['hello', 'reactive'];
const EXTRA_APPS = ['boundary', 'stores'];
const n = (x: number) => x.toLocaleString('en-US');
const pct = (x: number, base: number) => `${x - base >= 0 ? '+' : '−'}${Math.abs((100 * (x - base)) / base).toFixed(1)}%`;
const delta = (x: number, base: number) => (x === base ? '0' : `${x - base > 0 ? '+' : '−'}${n(Math.abs(x - base))}`);

const reports = new Map<string, Report>();
async function r(variant: string, app: string) {
	const key = `${variant}/${app}`;
	if (!reports.has(key)) reports.set(key, await loadReport(variant, app));
	return reports.get(key)!;
}
const size = async (variant: string, app: string) => (await r(variant, app)).sizes['main.min.js'];

const md: string[] = ['<!-- generated by scripts/comparison.ts; do not edit below this line by hand -->', ''];

// 1. app x variant
async function sizeTable(apps: string[]) {
	md.push('| app | variant | raw | gzip | brotli | Δ raw vs baseline | Δ gzip | Δ brotli |', '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |');
	for (const app of apps) {
		const base = await size('baseline', app);
		for (const v of ['baseline', 'optimized', 'minimal']) {
			const s = await size(v, app);
			const d = (k: 'raw' | 'gzip' | 'brotli') => (v === 'baseline' ? '' : `${delta(s[k], base[k])} (${pct(s[k], base[k])})`);
			md.push(`| ${app} | ${v === 'minimal' ? '**minimal**' : v} | ${n(s.raw)} | ${n(s.gzip)} | ${n(s.brotli)} | ${d('raw')} | ${d('gzip')} | ${d('brotli')} |`);
		}
	}
	md.push('');
}

md.push('## Sizes: app × variant (`main.min.js`)', '');
await sizeTable(MAIN_APPS);

// 2. stacking
md.push('## Stacking: one feature drop at a time on top of `optimized`', '');
md.push('Each row adds one technique to the row above; Δ is the marginal saving of that step (negative = smaller).', '');
md.push('| step | variant | hello min | Δ min | hello gzip | Δ gzip | reactive min | Δ min | reactive gzip | Δ gzip |', '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
const LABEL: Record<string, string> = {
	baseline: 'vanilla',
	optimized: 'lossless build fixes',
	'm1-legacy': '+ drop legacy mode',
	'm2-async': '+ drop async',
	'm3-transitions': '+ drop transitions/animations',
	'm4-boundary': '+ skip root boundary',
	'm5-delegation': '+ lazy event delegation',
	minimal: '+ tree-shakable $state proxy'
};
let prev: Record<string, { raw: number; gzip: number }> = {};
for (const v of STACK_ORDER) {
	const cells: string[] = [];
	for (const app of MAIN_APPS) {
		const s = await size(v, app);
		const p = prev[app];
		cells.push(n(s.raw), p ? delta(s.raw, p.raw) : '', n(s.gzip), p ? delta(s.gzip, p.gzip) : '');
		prev[app] = s;
	}
	md.push(`| ${LABEL[v] ?? v} | \`${v}\` | ${cells.join(' | ')} |`);
}
md.push('');

// 3. what still ships in minimal
md.push('## What still ships in `minimal`', '');
for (const app of MAIN_APPS) {
	const rep = await r('minimal', app);
	const total = rep.sizes['main.min.js'].raw;
	const covFile = join(resolve(ROOT, process.env.SVELTE_LITE_DIST ?? 'dist'), 'minimal', app, 'coverage.json');
	const cov = existsSync(covFile) ? await Bun.file(covFile).json() : null;
	md.push(`### ${app} (${n(total)} B min, ${n(rep.sizes['main.min.js'].gzip)} B gzip)`, '');
	if (cov) {
		const s = cov.byStatus;
		md.push(
			`Coverage while hydrating + running the app test: **ran ${n(s['ran'] ?? 0)} B**, never ran ${n(s['never ran'] ?? 0)} B, module-init data ${n(s['module init'] ?? 0)} B.`,
			''
		);
	}
	md.push('| category | min B | share | gzip Δ (if removed) |', '| --- | ---: | ---: | ---: |');
	for (const c of rep.categories.filter((c) => c.min > 0).slice(0, 10)) {
		md.push(`| ${c.category} | ${n(c.min)} | ${((100 * c.min) / total).toFixed(1)}% | ${n(c.gzipMarginal)} |`);
	}
	md.push('', '| top modules | min B | gzip Δ |', '| --- | ---: | ---: |');
	for (const m of rep.modules.filter((m) => m.min > 0).slice(0, 10)) {
		md.push(`| \`${m.module.replace(/^svelte\/src\//, '')}\` | ${n(m.min)} | ${n(m.gzipMarginal)} |`);
	}
	if (cov) {
		md.push('', '| largest functions/methods that never ran | min B |', '| --- | ---: |');
		for (const row of cov.rows.filter((x: any) => x.status === 'never ran').sort((a: any, b: any) => b.minBytes - a.minBytes).slice(0, 10)) {
			md.push(`| \`${row.name}\` (${row.module.replace(/^svelte\/src\//, '')}) | ${n(row.minBytes)} |`);
		}
	}
	md.push('');
}

// 4. extra verification apps
md.push('## Verification apps (sizes for reference)', '');
md.push('`boundary` exercises `<svelte:boundary>` failed/onerror/reset after hydration; `stores` exercises stores in runes mode, `{#each $store}` with in-place mutation and `$effect.pre` writing state during traversal. Both pass the same behavioural checks in every variant.', '');
await sizeTable(EXTRA_APPS);

// provenance, right below the marker: which Svelte every summarised report was built from
const sources = new Map<string, string[]>();
for (const [key, rep] of reports) {
	const src = rep.svelte ? `Svelte ${rep.svelte.version} (${provenanceText(rep.svelte)})` : `Svelte ${rep.svelteVersion} (exact source not recorded: built before svelte-ref.json)`;
	sources.set(src, [...(sources.get(src) ?? []), key]);
}
const stamp =
	sources.size === 1
		? [`Built from ${[...sources.keys()][0]} with Bun ${[...reports.values()][0].bunVersion}.`, '']
		: ['**Warning: these reports were built from different Svelte sources:**', '', ...[...sources].map(([src, keys]) => `- ${src}: ${keys.join(', ')}`), ''];
md.splice(2, 0, ...stamp);

const outArg = process.argv.find((a) => a.startsWith('--out='))?.slice('--out='.length);
const out = outArg ? resolve(outArg) : join(ROOT, 'COMPARISON.md');
const existing = await Bun.file(existsSync(out) ? out : join(ROOT, 'COMPARISON.md')).text().catch(() => '');
const marker = md[0];
const head = existing.includes(marker) ? existing.slice(0, existing.indexOf(marker)) : '# COMPARISON\n\n';
await Bun.write(out, head + md.join('\n') + '\n');
console.log(`wrote ${out}`);
